from pydantic import BaseModel, Field
from typing import Literal




class AgentSchema(BaseModel):
    messages: list = Field(default_factory=list, description="List of messages to be processed by the agent")
    
    user_query: str = Field(default="", description="User's original query that needs to be answered by the agent")
    curated_ques: str = Field(default="", description="Curated question for the agent to answer")
    
    prompt_query_context: str = Field(default="", description="Detailed prompt with SQL DB context that will help agent to generate SQL Query")
    is_safe: Literal["Yes", "No"] = Field( default="No", description="Indicates whether the generated SQL Query is safe (read-only) to execute or not")
    comments: str = Field(default="", description="Comments or feedback provided by the agent regarding the safety of the SQL Query")
    
    generated_sql_query: str = Field(default="", description="SQL Query generated by the agent based on the curated question and prompt query context")
    sql_query_result: str = Field(default="", description="Result of executing the SQL Query generated by the agent")
    sql_execution_success: bool = Field(default=False, description="Indicates whether the execution of the SQL Query was successful or not")
    sql_execution_error: str|None = Field(default=None, description="Error message if the execution of the SQL Query failed")
    
    final_answer: str = Field(default="", description="Final answer generated by the agent based on the SQL Query result and curated question")
    
    schema_details: str = Field(default="", description="Tell which schema details are used by the agent to generate SQL Query and final answer")


class JudgeSchema(BaseModel):
    is_safe: Literal["Yes", "No"] = Field(description="Indicates whether the generated SQL Query is safe (read-only) to execute or not")
    comments: str = Field(description="Comments or feedback provided by the agent regarding the safety of the SQL Query")


class ETLAgentSchema(BaseModel):
    messages: list = Field(default_factory=list, description="List of messages to be processed by the agent")


class DataAgentSchema(BaseModel):
    messages: list = Field(default_factory=list, description="List of messages to be processed by the agent")
    user_query: str = Field(default="", description="User's original query that needs to be answered by the agent")

    ticker: str = Field(default="", description="Ticker symbol of the company for which data is requested")
    requested_datasets: list[str] = Field(default_factory=list, description="List of datasets requested by the user")
    required_periods: list[int] = Field(default_factory=list, description="List of periods (years) requested by the user")

    available_data: dict = Field(default_factory=dict, description="Dictionary containing available data for each requested dataset and period")
    missing_data: dict = Field(default_factory=dict, description="Dictionary containing missing data for each requested dataset and period")

    next_action: Literal[
        "inspect_data",
        "query_database",
        "fetch_missing_data",
        "verify_result",
        "finish",
        "fail",
    ] = "inspect_data"

    observations: list[str] = Field(default_factory=list, description="List of observations made by the agent during the data processing")
    attempts: int = Field(default=0, description="Number of attempts made by the agent to fetch missing data")
    max_attempts: int = Field(default=3, description="Maximum number of attempts allowed for the agent to fetch missing data")
    
    sql_query_result: str = Field(default="", description="Result of executing the SQL Query generated by the agent")
    generated_sql_query: str = Field(default="", description="SQL Query generated by the agent based on the curated question and prompt query context")
    sql_attempts: int = Field(default=0, description="Number of attempts made by the agent to generate a safe SQL query")
    max_sql_attempts: int = Field(default=3, description="Maximum number of attempts allowed for the agent to generate a safe SQL query")
    
    sql_execution_success: bool = Field(default=False, description="Indicates whether the execution of the SQL Query was successful or not")
    sql_error: str | None = None

    verification_passed: bool = Field(default=False, description="Indicates whether the verification of the SQL query result passed or failed")
    verification_reason: str = Field(default="", description="Reason for the verification result")
    
    router_response: Literal["sql", "etl"] | None = Field(default=None, description="Indicates whether the router decided to use SQL or ETL for processing the user's query")
    final_answer: str = Field(default="", description="Final answer generated by the agent based on the SQL Query result and curated question")



class ETLLoadOutcome(BaseModel):
    ticker: str
    dataset: str
    status: Literal["SUCCESS", "PARTIAL", "UNAVAILABLE", "FAILED"]
    loaded_years: list[int] = Field(default_factory=list)
    missing_years: list[int] = Field(default_factory=list)
    error_message: str | None = None


class QueryExtractionSchema(BaseModel):
    ticker: str = Field(
        default="",
        description="Stock ticker symbol in uppercase, e.g., 'AAPL', 'MSFT', 'TSLA'. If not identified, leave empty.",
    )
    datasets: list[Literal["companies","income_statement", "balance_sheet", "cash_flow_statement"]] = Field(
        default_factory=list,
        description="Relevant  datasets requested or implied by the query.",
    )
    periods: list[int] = Field(
        default_factory=list,
        description="Calendar or fiscal years explicitly mentioned or deduced from the query, e.g., [2022, 2023, 2024].",
    )
