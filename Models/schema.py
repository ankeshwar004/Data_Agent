from pydantic import BaseModel, Field
from typing import Literal




class AgentSchema(BaseModel):
    messages: list = Field(
        default_factory=list,
        description="List of messages to be processed by the agent",
    )
    user_query: str = Field(
        default="",
        description="User's original query that needs to be answered by the agent",
    )
    curated_ques: str = Field(
        default="",
        description="Curated question for the agent to answer",
    )
    prompt_query_context: str = Field(
        default="",
        description="Detailed prompt with SQL DB context that will help agent to generate SQL Query",
    )
    is_safe: Literal["Yes", "No"] = Field(
        default="No",
        description="Indicates whether the generated SQL Query is safe to execute or not",
    )
    comments: str = Field(
        default="",
        description="Comments or feedback provided by the agent regarding the safety of the SQL Query",
    )
    generated_sql_query: str = Field(
        default="",
        description="SQL Query generated by the agent based on the curated question and prompt query context",
    )
    sql_query_result: str = Field(
        default="",
        description="Result of executing the SQL Query generated by the agent",
    )
    final_answer: str = Field(
        default="",
        description="Final answer generated by the agent based on the SQL Query result and curated question",
    )
    schema_details: str = Field(
        default="",
        description="Tell which schema details are used by the agent to generate SQL Query and final answer",
    )


class JudgeSchema(BaseModel):
    is_safe: Literal["Yes", "No"] = Field(description="Indicates whether the generated SQL Query is safe to execute or not")
    comments: str = Field(description="Comments or feedback provided by the agent regarding the safety of the SQL Query")


class ETLAgentSchema(BaseModel):
    messages: list = Field(
        default_factory=list,
        description="List of messages to be processed by the agent",
    )


class RouterSchema(BaseModel):
    answer: Literal["sql", "etl"] = Field(description="Indicates whether the agent is a SQL agent or an ETL agent")
    comments: str = Field(description="Comments or feedback provided by the agent regarding the routing decision")



class DataAgentSchema(BaseModel):
    messages: list = Field(default_factory=list,description="List of messages to be processed by the agent")
    user_query: str = Field(default="",description="User's original query that needs to be answered by the agent")

    ticker: str = ""
    requested_datasets: list[str] = Field(default_factory=list,description="List of datasets requested by the user")
    required_periods: list[int] = Field(default_factory=list)

    available_data: dict = Field(default_factory=dict)
    missing_data: dict = Field(default_factory=dict)

    next_action: Literal[
        "inspect_data",
        "query_database",
        "fetch_missing_data",
        "verify_result",
        "finish",
        "fail",
    ] = "inspect_data"

    observations: list[str] = Field(default_factory=list,description="List of observations made by the agent during the data processing")
    attempts: int = 0
    max_attempts: int = 3

    verification_passed: bool = False
    router_response: Literal["sql", "etl"] | None = None
    final_answer: str = ""



class ETLLoadOutcome(BaseModel):
    ticker: str
    dataset: str
    status: Literal["SUCCESS", "PARTIAL", "UNAVAILABLE", "FAILED"]
    loaded_years: list[int] = Field(default_factory=list)
    missing_years: list[int] = Field(default_factory=list)
    error_message: str | None = None


class QueryExtractionSchema(BaseModel):
    ticker: str = Field(
        default="",
        description="Stock ticker symbol in uppercase, e.g., 'AAPL', 'MSFT', 'TSLA'. If not identified, leave empty.",
    )
    datasets: list[Literal["income_statement", "balance_sheet", "cash_flow_statement"]] = Field(
        default_factory=list,
        description="Relevant financial statement datasets requested or implied by the query.",
    )
    periods: list[int] = Field(
        default_factory=list,
        description="Calendar or fiscal years explicitly mentioned or deduced from the query, e.g., [2022, 2023, 2024].",
    )
